#!/usr/bin/env python3
"""Rebuild hex.ico (and hex.rc) from Hex.png.

    python scripts/make-icon.py                 # hex.ico + hex.rc
    rc.exe /nologo /fo hex.res hex.rc           # then the .res build.ps1 links

Hex.png is the source of truth for the app icon. It is black line art on a
transparent 500x500 canvas, so it cannot be used as-is:

* the mark only covers ~35% of the canvas, so every size is cropped to the art;
* black-on-transparent vanishes on a dark taskbar, so the mark is drawn in the
  HUD's cream (#F9F4EB) on the HUD's plate colour (#111114) as an app tile;
* the hairlines fall below one pixel at 16-48 px, so those sizes are rendered
  from a dilated copy.

Sizes cover the title bar, taskbar and Alt-Tab (16-48) plus the shell's large
views (64-256).
"""

import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFilter

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "Hex.png"
ICON = ROOT / "hex.ico"
RC = ROOT / "hex.rc"

SIZES = [16, 20, 24, 32, 40, 48, 64, 128, 256]

PLATE = (17, 17, 20, 255)  # HUD plate colour
MARK = (249, 244, 235, 255)  # HUD dot colour
MARK_SCALE = 0.72  # mark occupies 72% of the tile, padding all round
PLATE_RADIUS = 0.22  # fraction of the tile


def mark_layer(size: int) -> Image.Image:
    """The art, cropped to its bounds, tinted cream, at `size` px square."""
    src = Image.open(SOURCE).convert("RGBA")
    alpha = src.getchannel("A")
    # Ignore the faint scatter when cropping: alpha > 8 is the drawn mark.
    bounds = alpha.point(lambda v: 255 if v > 8 else 0).getbbox()
    if bounds is None:
        raise SystemExit(f"{SOURCE} has no visible pixels")
    bw, bh = bounds[2] - bounds[0], bounds[3] - bounds[1]
    side = int(max(bw, bh) * 1.10)
    cx = (bounds[0] + bounds[2]) // 2
    cy = (bounds[1] + bounds[3]) // 2
    crop = src.crop((cx - side // 2, cy - side // 2, cx + side // 2, cy + side // 2))

    tinted = Image.new("RGBA", crop.size, MARK)
    tinted.putalpha(crop.getchannel("A"))

    # Render 4x and dilate before the final downscale: a 1 px hairline at 500 px
    # is ~0.05 px at 16 px and would disappear entirely.
    big = tinted.resize((size * 4, size * 4), Image.LANCZOS)
    if size < 48:
        big.putalpha(big.getchannel("A").filter(ImageFilter.MaxFilter(3)))
    return big.resize((size, size), Image.LANCZOS)


def tile(size: int) -> Image.Image:
    """One app-tile frame: rounded plate with the mark centred on it."""
    img = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    draw = ImageDraw.Draw(img)
    draw.rounded_rectangle(
        (0, 0, size - 1, size - 1),
        radius=max(2, int(size * PLATE_RADIUS)),
        fill=PLATE,
    )
    inner = max(8, int(size * MARK_SCALE))
    img.alpha_composite(mark_layer(inner), ((size - inner) // 2, (size - inner) // 2))
    return img


def main() -> int:
    if not SOURCE.exists():
        print(f"missing source image: {SOURCE}", file=sys.stderr)
        return 1

    frames = [tile(s) for s in SIZES]
    frames[-1].save(
        ICON,
        format="ICO",
        sizes=[(s, s) for s in SIZES],
        append_images=frames[:-1],
    )

    # Group icon id 1: LoadIconW(instance, MAKEINTRESOURCEW(1)) in src/hud.odin
    # and the shell's default-exe icon both read this. No includes, so a bare
    # rc.exe with no INCLUDE environment can compile it.
    RC.write_text(
        "// Generated by scripts/make-icon.py from Hex.png. Do not edit by hand.\n"
        "\n"
        '1 ICON "hex.ico"\n',
        encoding="utf-8",
    )

    print(f"wrote {ICON.relative_to(ROOT)} ({', '.join(f'{s}x{s}' for s in SIZES)})")
    print(f"wrote {RC.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
